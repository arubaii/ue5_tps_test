void UK2Node_SetStateMachineInput::CreateValuePin(EWidgetAnimMachineInputType Type)
{
	if (Type == EWidgetAnimMachineInputType::Trigger)
	{
		return;
	}

	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	UEdGraphPin* ValuePin = nullptr;
	if (Type == EWidgetAnimMachineInputType::Bool || Type == EWidgetAnimMachineInputType::Hold)
	{
		// Named bValue on the function; the pin keeps one name whatever its type, and expansion maps it. A Press And Hold
		// takes a bool too: true presses it, false lets go.
		ValuePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, ValuePinName);
	}
	else if (Type == EWidgetAnimMachineInputType::Integer)
	{
		ValuePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Int, ValuePinName);
	}
	else if (Type == EWidgetAnimMachineInputType::Choice)
	{
		// The option's name - picked from the input's options (see the pin's dropdown), or wired in.
		ValuePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Name, ValuePinName);
	}
	else if (Type == EWidgetAnimMachineInputType::Vector2D)
	{
		ValuePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Struct, TBaseStructure<FVector2D>::Get(), ValuePinName);
	}
	else
	{
		ValuePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Double, ValuePinName);
	}
	ValuePin->PinToolTip = LOCTEXT("ValueTip", "Value\nWhat the input is set to. Its type is the picked input's.").ToString();
	Schema->SetPinAutogeneratedDefaultValueBasedOnType(ValuePin);
}

void UK2Node_SetStateMachineInput::AllocateDefaultPins()
{
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();

	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* TargetPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UObject::StaticClass(), TargetPinName);
	TargetPin->bDefaultValueIsIgnored = true;
	TargetPin->PinToolTip = LOCTEXT("TargetTip", "Target\nThe widget whose state machine takes the input - one with a Widget Animation State Machine Component playing it, or one with such widgets inside it. Self when left unconnected.").ToString();

	UEdGraphPin* MachinePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_String, StateMachinePinName);
	MachinePin->bNotConnectable = true;
	MachinePin->PinToolTip = LOCTEXT("MachineTip", "State Machine\nOne of the state machines the Widget Animation State Machine Components on the Target and inside it play.").ToString();

	UEdGraphPin* InputPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Name, InputPinName);
	InputPin->PinToolTip = LOCTEXT("InputTip", "Input\nOne of the State Machine's inputs. Connect a name to set it by name instead - the Value pin then stays as it is.").ToString();

	CreateValuePin(InputType);

	UEdGraphPin* AllPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SetAllMatchesPinName);
	AllPin->PinToolTip = LOCTEXT("SetAllTip", "Set All Matches\nOff: sets the input on the first widget found on or under the Target that plays the machine. On: on every one - for a screen of many buttons.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(AllPin, TEXT("false"));

	UEdGraphPin* SearchPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SearchParentWidgetsPinName);
	SearchPin->bAdvancedView = true;
	SearchPin->PinToolTip = LOCTEXT("SearchTip", "Search Parent Widgets\nFrom a widget with no machine on or under it, looks outwards until one has it.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(SearchPin, TEXT("true"));

	UEdGraphPin* ReturnPin = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Boolean, UEdGraphSchema_K2::PN_ReturnValue);
	ReturnPin->PinToolTip = LOCTEXT("ReturnTip", "Return Value\nWhether a machine had the input.").ToString();

	if (AdvancedPinDisplay == ENodeAdvancedPins::NoPins)
	{
		AdvancedPinDisplay = ENodeAdvancedPins::Hidden;
	}

	Super::AllocateDefaultPins();
}

void UK2Node_SetStateMachineInput::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	// The Value pin takes the picked input's type as it stands now - the input may have changed type since this node was saved.
	const UEdGraphPin* OldTarget = nullptr;
	FString MachineKey;
	FName Name;
	for (const UEdGraphPin* Pin : OldPins)
	{
		if (Pin->PinName == TargetPinName)
		{
			OldTarget = Pin;
		}
		else if (Pin->PinName == StateMachinePinName)
		{
			MachineKey = Pin->DefaultValue;
		}
		else if (Pin->PinName == InputPinName && Pin->LinkedTo.Num() == 0)
		{
			Name = FName(*Pin->DefaultValue);
		}
	}

	EWidgetAnimMachineInputType Found = InputType;
	if (FindInputType(OldTarget, MachineKey, Name, Found))
	{
		InputType = Found;
	}

	Super::ReallocatePinsDuringReconstruction(OldPins);
}

void UK2Node_SetStateMachineInput::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (!Pin)
	{
		return;
	}

	if (Pin->PinName == StateMachinePinName)
	{
		// Another machine: keep the input if it has one by that name, else take its first.
		UEdGraphPin* InputPin = FindPin(InputPinName);
		TArray<TPair<FName, EWidgetAnimMachineInputType>> Inputs;
		GetInputChoices(Inputs);
		if (InputPin && InputPin->LinkedTo.Num() == 0)
		{
			const FName Current(*InputPin->DefaultValue);
			if (!Inputs.ContainsByPredicate([Current](const TPair<FName, EWidgetAnimMachineInputType>& Choice) { return Choice.Key == Current; }))
			{
				InputPin->DefaultValue = Inputs.Num() > 0 ? Inputs[0].Key.ToString() : FString();
			}
		}
		RefreshValuePin();
	}
	else if (Pin->PinName == InputPinName)
	{
		RefreshValuePin();
	}
}

void UK2Node_SetStateMachineInput::PinConnectionListChanged(UEdGraphPin* Pin)
{
	Super::PinConnectionListChanged(Pin);
	if (Pin && (Pin->PinName == TargetPinName || Pin->PinName == InputPinName))
	{
		RefreshValuePin();
	}
}

void UK2Node_SetStateMachineInput::RefreshValuePin()
{
	const UEdGraphPin* MachinePin = FindPin(StateMachinePinName);
	const UEdGraphPin* InputPin = FindPin(InputPinName);
	if (!MachinePin || !InputPin || InputPin->LinkedTo.Num() > 0)
	{
		return;
	}

	EWidgetAnimMachineInputType Found = InputType;
	if (!FindInputType(FindPin(TargetPinName), MachinePin->DefaultValue, FName(*InputPin->DefaultValue), Found) || Found == InputType)
	{
		return;
	}

	// The pin is made again for the new type - or taken away, for a Trigger - and whatever was wired in comes off.
	InputType = Found;
	if (UEdGraphPin* OldValuePin = FindPin(ValuePinName))
	{
		OldValuePin->Modify();
		OldValuePin->BreakAllPinLinks();
		RemovePin(OldValuePin);
	}
	CreateValuePin(InputType);

	// Back in its place, after Input.
	if (UEdGraphPin* NewValuePin = FindPin(ValuePinName))
	{
		const int32 InputIndex = Pins.IndexOfByKey(FindPin(InputPinName));
		Pins.Remove(NewValuePin);
		Pins.Insert(NewValuePin, InputIndex + 1);
	}

	GetGraph()->NotifyNodeChanged(this);
	if (UBlueprint* Blueprint = GetBlueprint())
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

