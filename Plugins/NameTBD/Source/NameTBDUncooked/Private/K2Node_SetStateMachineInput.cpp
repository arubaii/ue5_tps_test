void UK2Node_SetStateMachineInput::GatherChoices(const UEdGraphPin* TargetPin, TArray<FWidgetAnimMachineChoice>& OutChoices) const
{
	OutChoices.Reset();

	TArray<const UWidgetAnimationComponent*> Components;
	TArray<const UWidgetAnimationStateMachineComponent*> MachineComponents;
	UK2Node_SetWidgetAnimationValue::GatherComponentsInScope(UK2Node_SetWidgetAnimationValue::FindScopeFor(this, TargetPin), Components, &MachineComponents);

	// Every machine played in scope: a Widget Animation Component's - its own and the State Machine Component's it plays - and
	// the State Machine Components' the Blueprints store.
	TArray<const FWidgetAnimStateMachineEntry*> Rows;
	for (const UWidgetAnimationComponent* Component : Components)
	{
		TArray<const FWidgetAnimStateMachineEntry*> Played;
		Component->GetPlayedMachineRows(Played);
		Rows.Append(Played);
	}
	for (const UWidgetAnimationStateMachineComponent* MachineComponent : MachineComponents)
	{
		for (const FWidgetAnimStateMachineEntry& Row : MachineComponent->StateMachines)
		{
			Rows.Add(&Row);
		}
	}

	for (const FWidgetAnimStateMachineEntry* Row : Rows)
	{
		const UWidgetAnimStateMachineAsset* Machine = Row->StateMachine;
		if (!Machine)
		{
			continue;
		}
		const FString Key = Machine->GetPathName();
		if (OutChoices.ContainsByPredicate([&Key](const FWidgetAnimMachineChoice& Choice) { return Choice.Key == Key; }))
		{
			continue;
		}

		FWidgetAnimMachineChoice& Choice = OutChoices.AddDefaulted_GetRef();
		Choice.Key = Key;
		Choice.Label = FText::FromString(Machine->GetName());
		for (const FWidgetAnimMachineInput& Input : Machine->Inputs)
		{
			Choice.Inputs.Emplace(Input.Name, Input.Type);
		}
	}
}

void UK2Node_SetStateMachineInput::GetMachineChoices(TArray<FWidgetAnimMachineChoice>& OutChoices) const
{
	GatherChoices(FindPin(TargetPinName), OutChoices);
}

void UK2Node_SetStateMachineInput::GetInputChoices(TArray<TPair<FName, EWidgetAnimMachineInputType>>& OutInputs) const
{
	OutInputs.Reset();
	const UEdGraphPin* MachinePin = FindPin(StateMachinePinName);
	if (!MachinePin || MachinePin->DefaultValue.IsEmpty())
	{
		return;
	}

	TArray<FWidgetAnimMachineChoice> Choices;
	GetMachineChoices(Choices);
	if (const FWidgetAnimMachineChoice* Choice = Choices.FindByPredicate([MachinePin](const FWidgetAnimMachineChoice& Candidate) { return Candidate.Key == MachinePin->DefaultValue; }))
	{
		OutInputs = Choice->Inputs;
		return;
	}

	// Not on the Target (yet): the machine's own inputs, read from the asset itself.
	if (const UWidgetAnimStateMachineAsset* Machine = LoadObject<UWidgetAnimStateMachineAsset>(nullptr, *MachinePin->DefaultValue))
	{
		for (const FWidgetAnimMachineInput& Input : Machine->Inputs)
		{
			OutInputs.Emplace(Input.Name, Input.Type);
		}
	}
}

void UK2Node_SetStateMachineInput::GetChoiceOptions(TArray<FName>& OutOptions) const
{
	OutOptions.Reset();
	const UEdGraphPin* MachinePin = FindPin(StateMachinePinName);
	const UEdGraphPin* InputPin = FindPin(InputPinName);
	if (!MachinePin || !InputPin || MachinePin->DefaultValue.IsEmpty())
	{
		return;
	}
	const UWidgetAnimStateMachineAsset* Machine = LoadObject<UWidgetAnimStateMachineAsset>(nullptr, *MachinePin->DefaultValue);
	const FWidgetAnimMachineInput* Input = Machine ? Machine->FindInput(FName(*InputPin->DefaultValue)) : nullptr;
	if (Input && Input->Type == EWidgetAnimMachineInputType::Choice)
	{
		OutOptions = Input->Options;
	}
}

bool UK2Node_SetStateMachineInput::FindInputType(const UEdGraphPin* TargetPin, const FString& MachineKey, FName Name, EWidgetAnimMachineInputType& OutType) const
{
	if (MachineKey.IsEmpty() || Name.IsNone())
	{
		return false;
	}

	// The asset says what its inputs are, whether or not a component on the Target plays it.
	const UWidgetAnimStateMachineAsset* Machine = LoadObject<UWidgetAnimStateMachineAsset>(nullptr, *MachineKey);
	const FWidgetAnimMachineInput* Input = Machine ? Machine->FindInput(Name) : nullptr;
	if (!Input)
	{
		return false;
	}
	OutType = Input->Type;
	return true;
}

