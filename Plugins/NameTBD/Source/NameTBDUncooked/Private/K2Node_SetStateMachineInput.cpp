// The same names as UWidgetAnimStateMachineLibrary's parameters, so expansion moves each pin to its twin.
const FName UK2Node_SetStateMachineInput::TargetPinName(TEXT("Target"));
const FName UK2Node_SetStateMachineInput::StateMachinePinName(TEXT("StateMachine"));
const FName UK2Node_SetStateMachineInput::InputPinName(TEXT("Input"));
const FName UK2Node_SetStateMachineInput::ValuePinName(TEXT("Value"));
const FName UK2Node_SetStateMachineInput::SearchParentWidgetsPinName(TEXT("bSearchParentWidgets"));
const FName UK2Node_SetStateMachineInput::SetAllMatchesPinName(TEXT("bSetAllMatches"));

