void UK2Node_SetStateMachineInput::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UEdGraphPin* MachinePin = FindPin(StateMachinePinName);
	const UEdGraphPin* InputPin = FindPin(InputPinName);
	if (!MachinePin || !InputPin)
	{
		return;
	}

	if (MachinePin->DefaultValue.IsEmpty())
	{
		MessageLog.Warning(*LOCTEXT("NoMachine", "@@ has no State Machine picked: it sets the input on every machine that has it.").ToString(), this);
	}
	if (InputPin->LinkedTo.Num() > 0)
	{
		return;
	}

	const FName Name(*InputPin->DefaultValue);
	if (Name.IsNone())
	{
		MessageLog.Warning(*LOCTEXT("NoInput", "@@ has no Input: it sets nothing.").ToString(), this);
		return;
	}

	EWidgetAnimMachineInputType Found = InputType;
	if (!MachinePin->DefaultValue.IsEmpty() && !FindInputType(FindPin(TargetPinName), MachinePin->DefaultValue, Name, Found))
	{
		MessageLog.Warning(*FText::Format(LOCTEXT("MissingInput", "@@: '{0}' isn't one of the State Machine's inputs anymore - renamed or removed. It sets nothing."), FText::FromName(Name)).ToString(), this);
	}
	else if (Found != InputType)
	{
		MessageLog.Warning(*LOCTEXT("TypeChanged", "@@: the input's type has changed since this node was placed. Right-click it and choose Refresh Node to give it the new type.").ToString(), this);
	}
}

void UK2Node_SetStateMachineInput::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();

	FName FunctionName;
	FName FunctionValuePin;
	switch (InputType)
	{
	case EWidgetAnimMachineInputType::Trigger:
		FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimStateMachineLibrary, FireStateMachineTrigger);
		break;
	case EWidgetAnimMachineInputType::Number:
		FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimStateMachineLibrary, SetStateMachineNumber);
		FunctionValuePin = TEXT("Value");
		break;
	case EWidgetAnimMachineInputType::Integer:
		FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimStateMachineLibrary, SetStateMachineInteger);
		FunctionValuePin = TEXT("Value");
		break;
	case EWidgetAnimMachineInputType::Choice:
		FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimStateMachineLibrary, SetStateMachineChoice);
		FunctionValuePin = TEXT("Option");
		break;
	case EWidgetAnimMachineInputType::Vector2D:
		FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimStateMachineLibrary, SetStateMachineVector2D);
		FunctionValuePin = TEXT("Value");
		break;
	default:
		FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimStateMachineLibrary, SetStateMachineBool);
		FunctionValuePin = TEXT("bValue");
		break;
	}

	UK2Node_CallFunction* Call = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Call->FunctionReference.SetExternalMember(FunctionName, UWidgetAnimStateMachineLibrary::StaticClass());
	Call->AllocateDefaultPins();

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Call->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Call->GetThenPin());

	// Target: what is wired in, or Self.
	UEdGraphPin* TargetPin = FindPinChecked(TargetPinName);
	UEdGraphPin* CallTarget = Call->FindPinChecked(TargetPinName);
	if (TargetPin->LinkedTo.Num() > 0)
	{
		CompilerContext.MovePinLinksToIntermediate(*TargetPin, *CallTarget);
	}
	else
	{
		UK2Node_Self* Self = CompilerContext.SpawnIntermediateNode<UK2Node_Self>(this, SourceGraph);
		Self->AllocateDefaultPins();
		Schema->TryCreateConnection(Self->FindPinChecked(UEdGraphSchema_K2::PN_Self), CallTarget);
	}

	// The picked machine, as a literal. Nothing picked leaves it null: the input on any machine that has it.
	const FString MachineKey = FindPinChecked(StateMachinePinName)->DefaultValue;
	if (!MachineKey.IsEmpty())
	{
		UWidgetAnimStateMachineAsset* Machine = LoadObject<UWidgetAnimStateMachineAsset>(nullptr, *MachineKey);
		if (!Machine)
		{
			CompilerContext.MessageLog.Warning(*LOCTEXT("MachineMissing", "@@: its State Machine can't be found anymore, so it sets the input on any machine that has it.").ToString(), this);
		}
		Call->FindPinChecked(StateMachinePinName)->DefaultObject = Machine;
	}

	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(InputPinName), *Call->FindPinChecked(InputPinName));
	if (!FunctionValuePin.IsNone())
	{
		if (UEdGraphPin* ValuePin = FindPin(ValuePinName))
		{
			CompilerContext.MovePinLinksToIntermediate(*ValuePin, *Call->FindPinChecked(FunctionValuePin));
		}
	}
	for (const FName& PinName : { SearchParentWidgetsPinName, SetAllMatchesPinName, UEdGraphSchema_K2::PN_ReturnValue })
	{
		CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(PinName), *Call->FindPinChecked(PinName));
	}

	BreakAllNodeLinks();
}

