void UK2Node_SetWidgetAnimationValue::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UEdGraphPin* AnimationPin = FindPin(AnimationPinName);
	const UEdGraphPin* NamePin = FindPin(ValueNamePinName);
	if (!AnimationPin || !NamePin)
	{
		return;
	}

	if (AnimationPin->DefaultValue.IsEmpty())
	{
		MessageLog.Warning(*LOCTEXT("NoAnimation", "@@ has no Animation picked: it sets the Value Name in every animation that has it.").ToString(), this);
	}

	// A name wired in is only known at runtime.
	if (NamePin->LinkedTo.Num() > 0)
	{
		return;
	}

	const FName Name(*NamePin->DefaultValue);
	if (Name.IsNone())
	{
		MessageLog.Warning(*LOCTEXT("NoName", "@@ has no Value Name: it sets nothing.").ToString(), this);
		return;
	}

	EWidgetAnimValueKind Found = ValueKind;
	if (!AnimationPin->DefaultValue.IsEmpty() && !FindValueKind(FindPin(TargetPinName), AnimationPin->DefaultValue, Name, Found))
	{
		MessageLog.Warning(*FText::Format(LOCTEXT("MissingValue", "@@: '{0}' isn't a value-driven track's Value Name in the picked Animation anymore - renamed, removed, or no longer Value timed. It sets nothing."), FText::FromName(Name)).ToString(), this);
	}
	else if (Found != ValueKind)
	{
		MessageLog.Warning(*LOCTEXT("KindChanged", "@@: the track's Value Type has changed since this node was placed. Right-click it and choose Refresh Node to give its Value pin the new type.").ToString(), this);
	}
}

void UK2Node_SetWidgetAnimationValue::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();

	FName FunctionName;
	switch (ValueKind)
	{
	case EWidgetAnimValueKind::Integer:  FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimPlayLibrary, SetScopedValueInteger); break;
	case EWidgetAnimValueKind::Vector2D: FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimPlayLibrary, SetScopedValueVector2D); break;
	case EWidgetAnimValueKind::Color:    FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimPlayLibrary, SetScopedValueColor); break;
	default:                             FunctionName = GET_FUNCTION_NAME_CHECKED(UWidgetAnimPlayLibrary, SetScopedValueFloat); break;
	}

	UK2Node_CallFunction* Call = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Call->FunctionReference.SetExternalMember(FunctionName, UWidgetAnimPlayLibrary::StaticClass());
	Call->AllocateDefaultPins();

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Call->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Call->GetThenPin());

	// Target: what is wired in, or Self.
	UEdGraphPin* TargetPin = FindPinChecked(TargetPinName);
	UEdGraphPin* CallTarget = Call->FindPinChecked(TargetPinName);
	if (TargetPin->LinkedTo.Num() > 0)
	{
		CompilerContext.MovePinLinksToIntermediate(*TargetPin, *CallTarget);
	}
	else
	{
		UK2Node_Self* Self = CompilerContext.SpawnIntermediateNode<UK2Node_Self>(this, SourceGraph);
		Self->AllocateDefaultPins();
		Schema->TryCreateConnection(Self->FindPinChecked(UEdGraphSchema_K2::PN_Self), CallTarget);
	}

	// The picked animation, as a literal - or the additive tracks' flag. Nothing picked leaves both off: the name anywhere.
	const FString SourceKey = FindPinChecked(AnimationPinName)->DefaultValue;
	UEdGraphPin* CallAnimation = Call->FindPinChecked(AnimationPinName);
	UEdGraphPin* CallAdditive = Call->FindPinChecked(TEXT("bAdditiveTracks"));
	if (SourceKey == AdditiveTracksKey)
	{
		CallAdditive->DefaultValue = TEXT("true");
	}
	else if (!SourceKey.IsEmpty())
	{
		UWidgetAnimPresetAsset* Animation = LoadObject<UWidgetAnimPresetAsset>(nullptr, *SourceKey);
		if (!Animation)
		{
			CompilerContext.MessageLog.Warning(*LOCTEXT("AnimationMissing", "@@: its Animation can't be found anymore, so it sets the Value Name in every animation that has it.").ToString(), this);
		}
		CallAnimation->DefaultObject = Animation;
	}

	for (const FName& PinName : { ValueNamePinName, ValuePinName, SnapPinName, StartIfNotPlayingPinName, SearchParentWidgetsPinName, SetAllMatchesPinName, UEdGraphSchema_K2::PN_ReturnValue })
	{
		CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(PinName), *Call->FindPinChecked(PinName));
	}

	BreakAllNodeLinks();
}

