FEdGraphPinType UK2Node_SetWidgetAnimationValue::MakeValuePinType(EWidgetAnimValueKind Kind)
{
	FEdGraphPinType Type;
	switch (Kind)
	{
	case EWidgetAnimValueKind::Integer:
		Type.PinCategory = UEdGraphSchema_K2::PC_Int;
		break;

	case EWidgetAnimValueKind::Vector2D:
		Type.PinCategory = UEdGraphSchema_K2::PC_Struct;
		Type.PinSubCategoryObject = TBaseStructure<FVector2D>::Get();
		break;

	case EWidgetAnimValueKind::Color:
		Type.PinCategory = UEdGraphSchema_K2::PC_Struct;
		Type.PinSubCategoryObject = TBaseStructure<FLinearColor>::Get();
		break;

	default:
		// A Blueprint float is a double.
		Type.PinCategory = UEdGraphSchema_K2::PC_Real;
		Type.PinSubCategory = UEdGraphSchema_K2::PC_Double;
		break;
	}
	return Type;
}

void UK2Node_SetWidgetAnimationValue::AllocateDefaultPins()
{
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();

	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	// Self when left unconnected - see ExpandNode - so there is no default to pick.
	UEdGraphPin* TargetPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UObject::StaticClass(), TargetPinName);
	TargetPin->bDefaultValueIsIgnored = true;
	TargetPin->PinToolTip = LOCTEXT("TargetTip", "Target\nThe widget whose animations take the value - a widget with a Widget Animation Component, or any animation host. Self when left unconnected.").ToString();

	// A choice, never a wire: the dropdown lists what the widget's components play.
	UEdGraphPin* AnimationPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_String, AnimationPinName);
	AnimationPin->bNotConnectable = true;
	AnimationPin->PinToolTip = LOCTEXT("AnimationTip", "Animation\nThe Widget Animation the value belongs to - one of those played in Anim In and Anim Out by the Widget Animation Components on the Target and inside it - or their Additive Tracks.").ToString();

	UEdGraphPin* NamePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Name, ValueNamePinName);
	NamePin->PinToolTip = LOCTEXT("ValueNameTip", "Value Name\nThe value-driven track's Value Name, from those in the Animation. Connect a name to set it by name instead - the Value pin then stays as it is.").ToString();

	UEdGraphPin* ValuePin = CreatePin(EGPD_Input, MakeValuePinType(ValueKind), ValuePinName);
	ValuePin->PinToolTip = LOCTEXT("ValueTip", "Value\nWhere the tracks go: each maps it onto itself through its Value At Start and Value At End. Its type is the picked track's.").ToString();
	Schema->SetPinAutogeneratedDefaultValueBasedOnType(ValuePin);

	// Left in plain view: it decides how many widgets move, which is worth seeing on the node.
	UEdGraphPin* AllPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SetAllMatchesPinName);
	AllPin->PinToolTip = LOCTEXT("SetAllMatchesTip", "Set All Matches\nOff: sets the value in the first Widget Animation Component found on or under the Target that has it. On: in every one - for a screen holding many of the same widget.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(AllPin, TEXT("false"));

	UEdGraphPin* SnapPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SnapPinName);
	SnapPin->bAdvancedView = true;
	SnapPin->PinToolTip = LOCTEXT("SnapTip", "Snap\nJumps straight to the value, even back where a track never goes backwards - for resetting.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(SnapPin, TEXT("false"));

	UEdGraphPin* StartPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, StartIfNotPlayingPinName);
	StartPin->bAdvancedView = true;
	StartPin->PinToolTip = LOCTEXT("StartTip", "Start If Not Playing\nStarts the entry playing the Animation if it hasn't played yet, so no Play call is needed first. An entry already playing is never restarted.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(StartPin, TEXT("true"));

	UEdGraphPin* SearchPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SearchParentWidgetsPinName);
	SearchPin->bAdvancedView = true;
	SearchPin->PinToolTip = LOCTEXT("SearchTip", "Search Parent Widgets\nFrom a widget with no animations of its own, looks outwards until one has them.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(SearchPin, TEXT("true"));

	UEdGraphPin* ReturnPin = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Boolean, UEdGraphSchema_K2::PN_ReturnValue);
	ReturnPin->PinToolTip = LOCTEXT("ReturnTip", "Return Value\nWhether a running track took the value.").ToString();

	if (AdvancedPinDisplay == ENodeAdvancedPins::NoPins)
	{
		AdvancedPinDisplay = ENodeAdvancedPins::Hidden;
	}

	Super::AllocateDefaultPins();
}

void UK2Node_SetWidgetAnimationValue::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	// The Value pin takes the picked track's type as it stands now - the track may have changed type since this node
	// was saved - read off the old pins, before the new ones are made.
	const UEdGraphPin* OldTarget = nullptr;
	FString SourceKey;
	FName Name;
	for (const UEdGraphPin* Pin : OldPins)
	{
		if (Pin->PinName == TargetPinName)
		{
			OldTarget = Pin;
		}
		else if (Pin->PinName == AnimationPinName)
		{
			SourceKey = Pin->DefaultValue;
		}
		else if (Pin->PinName == ValueNamePinName && Pin->LinkedTo.Num() == 0)
		{
			Name = FName(*Pin->DefaultValue);
		}
	}

	EWidgetAnimValueKind Found = ValueKind;
	if (FindValueKind(OldTarget, SourceKey, Name, Found))
	{
		ValueKind = Found;
	}

	Super::ReallocatePinsDuringReconstruction(OldPins);
}

void UK2Node_SetWidgetAnimationValue::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);

	if (!Pin)
	{
		return;
	}

	if (Pin->PinName == AnimationPinName)
	{
		// Another animation: keep the name if it has one by that name, else take its first value - a name from the
		// old animation would only set nothing.
		UEdGraphPin* NamePin = FindPin(ValueNamePinName);
		TArray<FWidgetAnimValueChoice> Choices;
		GetValueChoices(Choices);
		if (NamePin && NamePin->LinkedTo.Num() == 0)
		{
			const FName Current(*NamePin->DefaultValue);
			if (!Choices.ContainsByPredicate([Current](const FWidgetAnimValueChoice& Choice) { return Choice.ValueName == Current; }))
			{
				NamePin->DefaultValue = Choices.Num() > 0 ? Choices[0].ValueName.ToString() : FString();
			}
		}
		RefreshValuePin();
	}
	else if (Pin->PinName == ValueNamePinName)
	{
		RefreshValuePin();
	}
}

void UK2Node_SetWidgetAnimationValue::PinConnectionListChanged(UEdGraphPin* Pin)
{
	Super::PinConnectionListChanged(Pin);

	// Another widget is another list; a name wired in has no one type to show.
	if (Pin && (Pin->PinName == TargetPinName || Pin->PinName == ValueNamePinName))
	{
		RefreshValuePin();
	}
}

void UK2Node_SetWidgetAnimationValue::RefreshValuePin()
{
	const UEdGraphPin* AnimationPin = FindPin(AnimationPinName);
	const UEdGraphPin* NamePin = FindPin(ValueNamePinName);
	UEdGraphPin* ValuePin = FindPin(ValuePinName);
	if (!AnimationPin || !NamePin || !ValuePin || NamePin->LinkedTo.Num() > 0)
	{
		return;
	}

	EWidgetAnimValueKind Found = ValueKind;
	if (!FindValueKind(FindPin(TargetPinName), AnimationPin->DefaultValue, FName(*NamePin->DefaultValue), Found) || Found == ValueKind)
	{
		return;
	}

	// Changed in place, as Get Data Table Row changes its row pin: whatever was wired in of the old type comes off.
	ValueKind = Found;
	ValuePin->Modify();
	ValuePin->PinType = MakeValuePinType(ValueKind);
	ValuePin->BreakAllPinLinks();
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValueBasedOnType(ValuePin);

	GetGraph()->NotifyNodeChanged(this);
	if (UBlueprint* Blueprint = GetBlueprint())
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

