// The same name as UWidgetAnimPlayLibrary::SetScopedProgress's parameter, so expansion moves the pin to its twin.
const FName UK2Node_SetWidgetAnimationProgress::ProgressPinName(TEXT("Progress"));

void UK2Node_SetWidgetAnimationProgress::AllocateDefaultPins()
{
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();

	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* TargetPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UObject::StaticClass(), TargetPinName);
	TargetPin->bDefaultValueIsIgnored = true;
	TargetPin->PinToolTip = LOCTEXT("TargetTip", "Target\nThe widget whose animation takes the progress - a widget with a Widget Animation Component, or any animation host. Self when left unconnected.").ToString();

	UEdGraphPin* AnimationPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_String, AnimationPinName);
	AnimationPin->bNotConnectable = true;
	AnimationPin->PinToolTip = LOCTEXT("AnimationTip", "Animation\nThe percentage animation (Time In Percent) to move - one of those played in Anim In and Anim Out by the Widget Animation Components on the Target and inside it.").ToString();

	// A Blueprint float is a double.
	UEdGraphPin* ProgressPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Double, ProgressPinName);
	ProgressPin->PinToolTip = LOCTEXT("ProgressTip", "Progress\nWhere the animation goes: 0 is 0%, 1 is 100%. Every track of it follows, travelling there by the animation's Smoothing.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(ProgressPin, TEXT("0.0"));

	UEdGraphPin* AllPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SetAllMatchesPinName);
	AllPin->PinToolTip = LOCTEXT("SetAllMatchesTip", "Set All Matches\nOff: sets the progress in the first Widget Animation Component found on or under the Target that plays the animation. On: in every one - for a screen holding many of the same widget.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(AllPin, TEXT("false"));

	UEdGraphPin* SnapPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SnapPinName);
	SnapPin->bAdvancedView = true;
	SnapPin->PinToolTip = LOCTEXT("SnapTip", "Snap\nJumps straight to the progress, even backwards where the animation never goes backwards - for resetting.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(SnapPin, TEXT("false"));

	UEdGraphPin* StartPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, StartIfNotPlayingPinName);
	StartPin->bAdvancedView = true;
	StartPin->PinToolTip = LOCTEXT("StartTip", "Start If Not Playing\nStarts the Anim In entry playing the animation if it hasn't played yet, so no Play call is needed first. An entry already playing is never restarted.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(StartPin, TEXT("true"));

	UEdGraphPin* SearchPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, SearchParentWidgetsPinName);
	SearchPin->bAdvancedView = true;
	SearchPin->PinToolTip = LOCTEXT("SearchTip", "Search Parent Widgets\nFrom a widget with no animations of its own, looks outwards until one has them.").ToString();
	Schema->SetPinAutogeneratedDefaultValue(SearchPin, TEXT("true"));

	UEdGraphPin* ReturnPin = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Boolean, UEdGraphSchema_K2::PN_ReturnValue);
	ReturnPin->PinToolTip = LOCTEXT("ReturnTip", "Return Value\nWhether a running animation took the progress.").ToString();

	if (AdvancedPinDisplay == ENodeAdvancedPins::NoPins)
	{
		AdvancedPinDisplay = ENodeAdvancedPins::Hidden;
	}

	// Not Super's: the Value node's pins are its own. The graph node's base still runs.
	UK2Node::AllocateDefaultPins();
}

void UK2Node_SetWidgetAnimationProgress::GetValueSources(TArray<FWidgetAnimValueSource>& OutSources) const
{
	Super::GetValueSources(OutSources);
	OutSources.RemoveAll([](const FWidgetAnimValueSource& Source) { return !Source.bPercent || Source.Key == AdditiveTracksKey; });
}

FText UK2Node_SetWidgetAnimationProgress::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	return LOCTEXT("Title", "Set Widget Animation Progress");
}

FText UK2Node_SetWidgetAnimationProgress::GetTooltipText() const
{
	return LOCTEXT("Tooltip", "Sets how far along a percentage animation (Time In Percent in the Widget Animations editor) is: pick the Animation, then give Progress, 0 for 0% and 1 for 100%. Every track of it follows - its keys, staggers, cues and the animations inserted into it. Call it as often as the progress changes: a hold timer, a charge level.\n\nLooks on the Target and inside it - into its child widgets and nested User Widgets - and sets the first Widget Animation Component that plays the animation, or every one with Set All Matches. Set Widget Animation Progress By Id sets it by an entry's Anim ID instead.");
}

