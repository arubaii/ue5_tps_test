void UK2Node_SetWidgetAnimationProgress::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	UK2Node::ValidateNodeDuringCompilation(MessageLog);

	const UEdGraphPin* AnimationPin = FindPin(AnimationPinName);
	if (!AnimationPin)
	{
		return;
	}

	if (AnimationPin->DefaultValue.IsEmpty())
	{
		MessageLog.Warning(*LOCTEXT("NoAnimation", "@@ has no Animation picked: it sets the progress of every percentage animation on the Target.").ToString(), this);
		return;
	}

	const UWidgetAnimPresetAsset* Animation = LoadObject<UWidgetAnimPresetAsset>(nullptr, *AnimationPin->DefaultValue);
	if (Animation && !Animation->IsPercentTime())
	{
		MessageLog.Warning(*FText::Format(LOCTEXT("NotPercent", "@@: {0} is no longer a percentage animation (its Time In is Seconds), so it sets nothing."), FText::FromString(Animation->GetName())).ToString(), this);
	}
}

void UK2Node_SetWidgetAnimationProgress::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	// Not Super's, which would expand to Set Widget Animation Value.
	UK2Node::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();

	UK2Node_CallFunction* Call = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Call->FunctionReference.SetExternalMember(GET_FUNCTION_NAME_CHECKED(UWidgetAnimPlayLibrary, SetScopedProgress), UWidgetAnimPlayLibrary::StaticClass());
	Call->AllocateDefaultPins();

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Call->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Call->GetThenPin());

	// Target: what is wired in, or Self.
	UEdGraphPin* TargetPin = FindPinChecked(TargetPinName);
	UEdGraphPin* CallTarget = Call->FindPinChecked(TargetPinName);
	if (TargetPin->LinkedTo.Num() > 0)
	{
		CompilerContext.MovePinLinksToIntermediate(*TargetPin, *CallTarget);
	}
	else
	{
		UK2Node_Self* Self = CompilerContext.SpawnIntermediateNode<UK2Node_Self>(this, SourceGraph);
		Self->AllocateDefaultPins();
		Schema->TryCreateConnection(Self->FindPinChecked(UEdGraphSchema_K2::PN_Self), CallTarget);
	}

	// The picked animation, as a literal. Nothing picked: every percentage animation on the Target.
	const FString SourceKey = FindPinChecked(AnimationPinName)->DefaultValue;
	if (!SourceKey.IsEmpty())
	{
		UWidgetAnimPresetAsset* Animation = LoadObject<UWidgetAnimPresetAsset>(nullptr, *SourceKey);
		if (!Animation)
		{
			CompilerContext.MessageLog.Warning(*LOCTEXT("AnimationMissing", "@@: its Animation can't be found anymore, so it sets the progress of every percentage animation on the Target.").ToString(), this);
		}
		Call->FindPinChecked(AnimationPinName)->DefaultObject = Animation;
	}

	for (const FName& PinName : { ProgressPinName, SnapPinName, StartIfNotPlayingPinName, SearchParentWidgetsPinName, SetAllMatchesPinName, UEdGraphSchema_K2::PN_ReturnValue })
	{
		CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(PinName), *Call->FindPinChecked(PinName));
	}

	BreakAllNodeLinks();
}

